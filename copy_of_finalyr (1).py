def generate_recommendations(negative_features):
    """
    negative_features: DataFrame with columns ['feature', 'shap_value']
    """
    recommendations = []

    features = negative_features["feature"].tolist()

    # Enrollment issue
    if any("Enrollment" in f for f in features):
        recommendations.append(
            "Increase planned enrollment or expand recruitment centers to reduce failure risk."
        )

    # Early phase
    if any("Phases_PHASE1" in f or "phase_num" in f for f in features):
        recommendations.append(
            "Consider conducting pilot studies or progressing to later trial phases."
        )

    # Sponsor reliability
    if any("sponsor_success_rate" in f for f in features):
        recommendations.append(
            "Collaborate with experienced industry sponsors or established research organizations."
        )

    # Risk words in text
    if any("risk_score" in f for f in features):
        recommendations.append(
            "Address recruitment delays, funding constraints, and operational risks before trial initiation."
        )

    # Long duration risk
    if any("Duration_days" in f or "duration_per_phase" in f for f in features):
        recommendations.append(
            "Optimize trial duration to improve feasibility while maintaining scientific rigor."
        )

    # Disease severity from text
    high_risk_terms = ["cancer", "severe", "rare", "terminal"]
    if any(any(term in f.lower() for term in high_risk_terms) for f in features):
        recommendations.append(
            "Implement enhanced safety monitoring and adaptive trial designs for high-risk conditions."
        )

    # Fallback
    if not recommendations:
        recommendations.append(
            "Trial design appears balanced; consider minor operational optimizations."
        )

    return recommendations

